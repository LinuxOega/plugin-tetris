/**
 * Generate the standalone front-end core from ui/src/core/tetris.js.
 *
 * The Node test suite imports the rules as an ES module; the static page
 * served through Halo's ReverseProxy needs a classic script. This script
 * strips `export` keywords, wraps the source in an IIFE and exposes the same
 * API as window.TetrisCore. No third-party dependency is required.
 *
 * Usage: node scripts/build-standalone.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(root, 'ui/src/core/tetris.js');
const outputPath = resolve(root, 'src/main/resources/static/tetris/tetris-core.js');

const source = readFileSync(sourcePath, 'utf8');

const exported = [...source.matchAll(/^export\s+(?:const|function|class)\s+([A-Za-z_$][\w$]*)/gm)]
  .map((match) => match[1]);

if (exported.length === 0) {
  throw new Error('No ESM exports found in tetris.js — standalone build aborted.');
}

const body = source
  .replace(/^export\s+(const|function|class)\s+/gm, '$1 ')
  .replace(/^export\s+\{[^}]*\};?\s*$/gm, '');

const banner = [
  '/* AUTO-GENERATED by scripts/build-standalone.mjs — DO NOT EDIT.',
  ' * Source of truth: ui/src/core/tetris.js',
  ' * Exposes window.TetrisCore for the standalone page. */',
].join('\n');

const output = `${banner}
(function (global) {
  'use strict';
${body.split('\n').map((line) => `  ${line}`).join('\n')}

  global.TetrisCore = {
${exported.map((name) => `    ${name}`).join(',\n')}
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;

writeFileSync(outputPath, output, 'utf8');
console.log(`[standalone] ${exported.length} exports -> ${outputPath}`);
