/**
 * Build a deploy-anywhere front-end pack for personal blogs.
 *
 * The Halo plugin is not required to play: the page under
 * src/main/resources/static/tetris is plain HTML/CSS/JS and already falls back
 * to a browser-local leaderboard. This script produces two artefacts:
 *
 *   standalone/tetris/     four files, linked with relative paths
 *   standalone/tetris.html one self-contained file (CSS + JS inlined, local mode)
 *
 * Run `node scripts/build-standalone.mjs` first whenever the rules change,
 * then `node scripts/build-blog-pack.mjs`.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const gameDir = resolve(root, 'src/main/resources/static/tetris');
const outDir = resolve(root, 'standalone');
const packDir = resolve(outDir, 'tetris');

const names = ['index.html', 'style.css', 'app.js', 'tetris-core.js'];
const src = Object.fromEntries(
  names.map((name) => [name, readFileSync(resolve(gameDir, name), 'utf8')])
);

mkdirSync(packDir, { recursive: true });
for (const name of names) {
  writeFileSync(resolve(packDir, name), src[name], 'utf8');
}

// A literal </script inside inlined JS would terminate the tag early.
const safeJs = (code) => code.replace(/<\/script/gi, '<\\/script');

const inlineJs = [
  '/* AUTO-GENERATED single-file build.',
  '   Edit src/main/resources/static/tetris/* and re-run scripts/build-blog-pack.mjs. */',
  "window.TETRIS_CONFIG = { mode: 'local' };",
  safeJs(src['tetris-core.js']),
  safeJs(src['app.js']),
].join('\n');

const banner = '<!-- AUTO-GENERATED by scripts/build-blog-pack.mjs — single-file Tetris for any blog -->';

let single = src['index.html']
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace(
    /<link rel="stylesheet" href="\.\/style\.css">/,
    () => `<style>\n${src['style.css']}\n</style>`
  )
  .replace(
    '<script src="./tetris-core.js"></script>',
    () => `<script>\n${inlineJs}\n</script>`
  )
  .replace('<script src="./app.js"></script>', '')
  .replace('<!doctype html>', () => `<!doctype html>\n${banner}`);

if (single.includes('<script src=') || single.includes('href="./style.css"')) {
  throw new Error('Inlining failed: external references remain in the single-file build.');
}
if (!single.includes("window.TETRIS_CONFIG = { mode: 'local' }")) {
  throw new Error('Inlining failed: local-mode config missing.');
}

writeFileSync(resolve(outDir, 'tetris.html'), single, 'utf8');

console.log(`[blog-pack] ${names.length} files -> ${packDir}`);
console.log(`[blog-pack] single file (${(Buffer.byteLength(single, 'utf8') / 1024).toFixed(1)} KB) -> ${resolve(outDir, 'tetris.html')}`);
